await page.getByText('حجم اصلی',{exact:true}).waitFor();
await page.evaluate(()=>{
  window.restoreStorage = Storage.prototype.setItem;
  Storage.prototype.setItem = function() { throw new DOMException('Quota reached','QuotaExceededError'); };
});
await page.getByRole('button',{name:'ذخیره و بارگذاری',exact:true}).click();
await page.getByRole('dialog').getByRole('alert').filter({hasText:'ذخیره نشد'}).waitFor();
assert.equal(await card.locator('.adm-thumb').count(), countBefore);
await page.evaluate(()=>{ Storage.prototype.setItem = window.restoreStorage; });
await page.getByRole('button',{name:'انصراف',exact:true}).click();
console.log('PASS: browser storage quota failure preserves prior gallery and shows Persian error');
assert.deepEqual(errors,[]);
console.log('PASS: no browser runtime errors');
await browser.close();
