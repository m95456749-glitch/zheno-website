// Real Chromium layout/decoder checks, Demo mode only — NOT Supabase E2E.
import { chromium as playwright } from 'playwright';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
mkdirSync('.qa', { recursive: true });
const browser = await playwright.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox', '--disable-dev-shm-usage'], headless: true });
const page = await browser.newPage({ viewport:{width:1440,height:1050} });
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto(`${process.env.IMAGE_TEST_BASE_URL || 'http://localhost:5173'}/admin/login`);
await page.locator('input[autocomplete="username"]').fill('مدیر آزمایشی');
await page.locator('input[type="password"]').fill('local-demo-only');
await page.locator('form').evaluate(form=>form.requestSubmit());
await page.waitForURL('**/admin/dashboard');
await page.locator('a[href="/admin/product-images"]').first().click();
await page.getByText('تصویر خوب، انتخاب دل‌چسب').waitFor();
await page.screenshot({path:'.qa/gallery-desktop.png',fullPage:false});
const card = page.locator('.adm-image-card').filter({hasText:'پودر ژله انار ژینو'});
await card.getByRole('button',{name:'بارگذاری تصویر',exact:true}).click();
await page.locator('input[type="file"]').setInputFiles('public/images/products/jelly-strawberry.jpg');
await page.getByText('حجم اصلی',{exact:true}).waitFor();
await page.getByRole('button',{name:'ذخیره و بارگذاری',exact:true}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
assert.equal(await card.locator('.adm-thumb').count(),2);
console.log('PASS: real Chromium decode, preview, Demo upload; existing legacy photo retained');
await card.locator('.adm-thumb').last().getByRole('button',{name:/انتخاب به‌عنوان/}).click();
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('zhino_admin_catalog_v1')).upserts['jelly-pomegranate'].imageUrl.startsWith('data:'));
await card.getByRole('button',{name:'جایگزینی تصویر اصلی',exact:true}).click();
await page.getByRole('switch',{name:'تصویر اصلی محصول شود',exact:true}).click();
await page.locator('input[type="file"]').setInputFiles('public/images/products/jelly-orange.jpg');
await page.getByText('حجم اصلی',{exact:true}).waitFor();
await page.getByRole('button',{name:'ذخیره و جایگزینی',exact:true}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
assert.equal(await card.locator('.adm-thumb').count(),3);
console.log('PASS: disabling make-primary never removes previous primary');
await page.reload();
await page.locator('input[autocomplete="username"]').fill('مدیر آزمایشی');
await page.locator('input[type="password"]').fill('local-demo-only');
await page.locator('form').evaluate(form=>form.requestSubmit());
await page.waitForURL('**/admin/dashboard');
await page.locator('a[href="/admin/product-images"]').first().click();
await card.waitFor();
assert.equal(await card.locator('.adm-thumb').count(),3);
console.log('PASS: Demo gallery survives refresh and re-login');
for (const width of [320,375,390,768,1024,1440]) {
 await page.setViewportSize({width,height:844});
 await page.waitForTimeout(150);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`page overflow at ${width}`);
 if(width===390) await page.screenshot({path:'.qa/gallery-mobile.png'});
 await card.getByRole('button',{name:'بارگذاری تصویر',exact:true}).click();
 await page.locator('input[type="file"]').setInputFiles('public/images/products/jelly-strawberry.jpg');
 await page.getByText('حجم اصلی',{exact:true}).waitFor();
 assert.ok(await page.locator('.adm-modal').evaluate(el=>el.scrollWidth<=el.clientWidth+1),`modal overflow at ${width}`);
 if(width===390) await page.screenshot({path:'.qa/upload-mobile.png'});
 await page.getByRole('button',{name:'انصراف',exact:true}).click();
 console.log(`PASS: actual Chromium layout at ${width}px — no horizontal page/modal overflow`);
}
await card.getByRole('button',{name:'بارگذاری تصویر',exact:true}).click();
await page.locator('input[type="file"]').setInputFiles({name:'broken.gif',mimeType:'image/gif',buffer:Buffer.from('GIF89a-broken')});
await page.getByRole('alert').filter({hasText:'معتبری نیست'}).waitFor();
assert.ok(await page.getByRole('button',{name:'ذخیره و بارگذاری',exact:true}).isDisabled());
console.log('PASS: genuine browser decoder rejects corrupt GIF; cannot submit');
await page.getByRole('button',{name:'انصراف',exact:true}).click();
const countBefore = await card.locator('.adm-thumb').count();
await card.getByRole('button',{name:'بارگذاری تصویر',exact:true}).click();
